const assert = require('node:assert/strict');
const ts = require('typescript');
const fs = require('node:fs');
const vm = require('node:vm');
function load(path, requireModule) {
  const output = ts.transpileModule(fs.readFileSync(path, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
  const sandbox = { exports: {}, require: requireModule, localStorage, window: { dispatchEvent() {} }, Event: class {}, Intl, Date, crypto: require("node:crypto") };
  vm.runInNewContext(output, sandbox);
  return sandbox.exports;
}
const memory = new Map();
const localStorage = { getItem: key => memory.get(key) || null, setItem: (key, value) => memory.set(key, value) };
const execution = load('lib/reading-execution.ts');
const store = load('lib/application-store.ts');
const { executionStatus, shiftDay, londonDay, validateReading, startCommitment, restartCommitment, stopCommitment, listCommitments } = execution;
for (const total of [1, 2, 100, 350, 351, 999]) {
  const plan = { bookId: 'b', totalPages: total, startDate: '2026-09-30' };
  const book = { id: 'b', currentPage: 0, totalPages: total };
  let sum = 0;
  for (let d = 0; d < 7; d++) {
    const status = executionStatus(plan, book, [], shiftDay(plan.startDate, d));
    sum += status.quota;
    assert.equal(status.pageTarget, Math.ceil(total * (d + 1) / 7));
  }
  assert.equal(sum, total);
  assert.equal(executionStatus(plan, book, [], '2026-10-07').overdue, true);
}
const plan = { bookId: 'b', totalPages: 350, startDate: '2026-09-30' };
const book = { id: 'b', currentPage: 50, totalPages: 350 };
const log = { bookId: 'b', pages: 50, createdAt: '2026-09-30T23:10:00Z' };
assert.equal(londonDay(new Date(log.createdAt)), '2026-10-01');
assert.equal(executionStatus(plan, book, [log], '2026-10-01').remainingToday, 0);
assert.equal(executionStatus(plan, book, [{ ...log, bookId: 'other' }], '2026-10-01').pagesToday, 0);
assert.equal(executionStatus(plan, book, [], '2026-10-02').behind, 50);
assert.ok(validateReading(book, 351));
assert.ok(validateReading(book, 50));
assert.ok(validateReading(book, 51.5));
assert.equal(validateReading(book, 51), null);
startCommitment('b', 350);
assert.equal(listCommitments().length, 1);
assert.throws(() => startCommitment('b', 350));
startCommitment('c', 210);
assert.equal(listCommitments().length, 2, 'Multiple books may be tracked at the same time');
restartCommitment('b', 360);
assert.equal(listCommitments().find(plan => plan.bookId === 'b').totalPages, 360);
stopCommitment('c');
assert.equal(listCommitments().length, 1);
assert.throws(() => startCommitment('c', 0));
store.saveBooks([{ ...book, completed: false }]);
store.saveBooks([{ ...book, currentPage: 350, completed: false }]);
assert.equal(store.loadBooks()[0].completed, true);
assert.ok(store.loadBooks()[0].readingFinishedAt);
console.log('Passed: seven-day pacing, London dates, book-specific credit, concurrent targets, restart/stop overrides, input bounds and completion timestamp.');

// Book lifecycle must preserve source IDs, old work and hidden books during ordinary shelf saves.
memory.clear();
const notesStore = load('lib/library-notes-store.ts');
assert.throws(() => store.createBook({title:'  ',totalPages:350}));
assert.throws(() => store.createBook({title:'Bad pages',totalPages:2.5}));
const completedAtCreation = store.createBook({title:'Already read',totalPages:350,currentPage:350});
assert.equal(completedAtCreation.completed,true,'A personal library may add a book already completed');
const first = store.createBook({title:'  A Life  ',author:'  Author  ',totalPages:350,currentPage:20});
const second = store.createBook({title:'A Life',totalPages:210});
assert.notEqual(first.id,second.id);
assert.equal(first.title,'A Life');
assert.equal(first.currentPage,20);
assert.equal(store.loadLogs().length,0);
const note = notesStore.addHighlight({sourceId:first.id,text:'Original quote'});
store.saveLogs([{id:'l',bookId:first.id,bookTitle:first.title,pages:25,minutes:15,date:'30/09/2026'}]);
store.updateBookDetails(first.id,{title:'Updated title',author:'Author',totalPages:350});
assert.equal(store.loadLogs()[0].bookTitle,'Updated title');
assert.equal(notesStore.listHighlights()[0].sourceId,first.id);
startCommitment(first.id,350);
store.updateBookDetails(first.id,{title:'Updated title',author:'Author',totalPages:351});
assert.equal(store.loadBooks({includeArchived:true,includeDeleted:true}).find(b=>b.id===first.id).totalPages,351);
assert.equal(listCommitments().find(plan=>plan.bookId===first.id).totalPages,351,'Correcting total pages updates the active pacing target');
const staleShelf=store.loadBooks();
store.setBookState(first.id,'archive');
assert.equal(store.loadBooks().length,1);
store.saveBooks(staleShelf);
assert.equal(store.loadBooks().length,1, 'A stale reading view must not unarchive a book');
store.saveBooks(store.loadBooks());
assert.equal(store.loadBooks({includeArchived:true}).length,2, 'Saving another shelf must retain the archive');
store.setBookState(first.id,'delete');
assert.equal(store.loadBooks({includeArchived:true}).length,1);
store.saveBooks(store.loadBooks());
assert.equal(store.loadBooks({includeArchived:true,includeDeleted:true}).length,2);
assert.equal(store.loadLogs()[0].bookId,first.id);
assert.equal(notesStore.listHighlights()[0].id,note.id);
assert.equal(listCommitments()[0].bookId,first.id);
store.setBookState(first.id,'restore');
assert.equal(store.loadBooks({includeArchived:true}).length,2);
assert.equal(store.loadBooks().length,1, 'Restoring a deleted archive entry must preserve its original shelf');
store.setBookState(first.id,'unarchive');
assert.equal(store.loadBooks().length,2);
assert.equal(store.loadBooks().find(b=>b.id===first.id).title,'Updated title');
console.log('Passed: direct creation, completed-book import, distinct IDs, metadata corrections, archive/trash/restore, stale shelf safety and preserved notes/logs/commitments.');

const folder = store.createBook({title:'An unread book'});
assert.equal(folder.currentPage,0);
assert.equal(folder.completed,false);
assert.equal(folder.highlights.length,0);
assert.equal(store.loadBooks().find(b=>b.id===folder.id).title,'An unread book');
store.updateBookDetails(folder.id,{title:'An unread book, renamed',author:''});
assert.equal(store.loadBooks().find(b=>b.id===folder.id).totalPages,1);
store.updateBookDetails(folder.id,{title:'An unread book, renamed',author:'Author',totalPages:280});
assert.equal(store.loadBooks().find(b=>b.id===folder.id).totalPages,280);
console.log('Passed: title-only folder creation, no notes/import requirement, and later page-count setup.');
